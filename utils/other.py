# =====================================================
# Plot Function
# =====================================================


def plot_metric(frozen_data, unfrozen_data,
                title, ylabel, save_name):

    plt.figure(figsize=(7, 5))

    plt.plot(
        epoch_frozen,
        frozen_data,
        marker='o',
        linewidth=2.2,
        markersize=4,
        label='Frozen Encoder'
    )

    plt.plot(
        epoch_unfrozen,
        unfrozen_data,
        marker='s',
        linewidth=2.2,
        markersize=4,
        label='Trainable Encoder'
    )

    plt.title(title, fontsize=15)
    plt.xlabel('Epoch', fontsize=13)
    plt.ylabel(ylabel, fontsize=13)

    plt.grid(True, linestyle='--', alpha=0.6)

    plt.legend(fontsize=11)

    plt.tight_layout()

    plt.savefig(
        f'{save_name}.png',
        dpi=300,
        bbox_inches='tight'
    )

    plt.savefig(
        f'{save_name}.pdf',
        bbox_inches='tight'
    )

    plt.show()

# =====================================================
